for (let i = 0; i < 20; i++) { await page.locator('.reveal-card').click().catch(() => {}); await page.waitForTimeout(700); if (await page.locator('.summary').count()) break; if (i === 17) await shot('pack-last', 300); }
await shot('pack-summary', 1500);
await browser.close();
