function roundSig(x: Decimal): Decimal {
  // 見栄えのため有効数字 2 桁に丸める
  const e = x.exponent;
  const m = Math.round(x.mantissa * 10) / 10;
  return Decimal.fromMantissaExponent(m, e);
}

