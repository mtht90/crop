export type IconName = keyof typeof paths;

export function iconSvg(name: string): string {
  return `<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${paths[name] ?? ''}</svg>`;
}

/** 要素の中身をアイコンにする (既存の子要素は保持しない) */
export function setIcon(el: Element, name: string): void {
  if (el.getAttribute('data-current-icon') === name) return;
  el.setAttribute('data-current-icon', name);
  const extra = [...el.children].filter((c) => c.tagName.toLowerCase() !== 'svg');
  el.innerHTML = iconSvg(name);
  extra.forEach((c) => el.appendChild(c));
}

export function icon(name: string): HTMLElement {
  const span = document.createElement('span');
  span.className = 'icon';
  span.innerHTML = iconSvg(name);
  return span;
}
