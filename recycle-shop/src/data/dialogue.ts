export type LineKey = keyof typeof LINES;

export function line(key: LineKey, vars: Record<string, string> = {}): string {
  let s = rng.pick(LINES[key]);
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
