"""Build historia/game/data.js and face-centred card art for set 1."""
import json, os, re, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'data')); sys.path.insert(0, os.path.join(ROOT, 'tools'))
from set1_content import P, T
from overrides import MANUAL, DROP
IMG = os.path.join(os.path.dirname(ROOT), 'card-assets', 'images')
base = json.load(open(os.path.join(ROOT, 'data', 'set1_base.json')))
base['persons'] = [c for c in base['persons'] if c['no'] not in DROP]
base['trainers'] = [c for c in base['trainers'] if c['no'] not in DROP]
faces = json.load(open(os.path.join(ROOT, 'data', 'faces_h01.json')))
TYPE = {'武勇':'buyu','知略':'chiryaku','政治':'seiji','科学':'kagaku','思想':'shiso','探検':'tanken','下剋上':'gekokujo','芸術':'geijutsu'}
WEAK = {'buyu':'chiryaku','chiryaku':'gekokujo','gekokujo':'seiji','seiji':'shiso','shiso':'kagaku','kagaku':'seiji','tanken':'buyu','geijutsu':'buyu'}
KIND = {'サポート':'support','グッズ':'goods','どうぐ':'tool','スタジアム':'stadium'}
STAGE = {'たね':0,'1進化':1,'2進化':2}
ART = os.path.join(ROOT, 'game', 'art'); os.makedirs(ART, exist_ok=True)
S = 400

def face_crop(fn):
    im = Image.open(os.path.join(IMG, fn)).convert('RGB'); W, H = im.size
    key = fn[4:7]
    if key in MANUAL:
        fx, fy, fwf = MANUAL[key]; cx, cy, fw = fx*W, fy*H, fwf*W
    else:
        v = faces.get(fn)
        if not v or not v['faces']:
            cx, cy, fw = W/2, H*0.3, W*0.3
        else:
            sc = W / v['W']; f = v['faces'][0]; cx, cy, fw = f['cx']*sc, f['cy']*sc, f['w']*sc
    h = min(H, W, max(fw/0.30, 200)); w = h
    x = min(max(cx - w/2, 0), W - w); y = min(max(cy - h*0.42, 0), H - h)
    return im.crop((int(x), int(y), int(x+w), int(y+h))).resize((S, S), Image.LANCZOS)

def center_crop(fn):
    im = Image.open(os.path.join(IMG, fn)).convert('RGB'); W, H = im.size; s = min(W, H)
    return im.crop(((W-s)//2, (H-s)//2, (W+s)//2, (H+s)//2)).resize((S, S), Image.LANCZOS)

def credit(c):
    a = (c.get('artist') or '').strip()
    a = re.sub(r'^(English|日本語):\s*', '', a)
    a = re.split(r'\s(?:English|日本語):|Description|Alternative names|Not identified', a)[0].strip()
    a = re.sub(r'\s*\(.*?\)\s*$', '', a)[:40] or '作者不詳'
    if re.match(r'(?i)^(unknown|anonymous|不明|不詳|作者不詳)', a): a = '作者不詳'
    lic = c.get('lic') or ''
    short = 'PD' if 'Public domain' in lic or 'PD' in lic or 'No restrictions' in lic else re.sub(r'（.*', '', lic)
    return a, short

cards = []
name2no = {}
for c in base['persons']:
    name2no[c['name']] = c['no']
for c in base['persons']:
    no = c['no']; hp, rar, ret, atks, flav = P[no]
    t = TYPE[c['type']]
    artfile = f"{no}.jpg"
    if not os.path.exists(os.path.join(ART, artfile)) or '--force' in sys.argv:
        face_crop(c['img']).save(os.path.join(ART, artfile), quality=84)
    a, lic = credit(c)
    cards.append(dict(id=no, kind='person', name=c['name'], type=t, stage=STAGE[c['stage']],
        from_=name2no.get(c['from']) if c['from'] else None, hp=hp, rar=rar, ret=ret, weak=WEAK[t],
        atks=[dict(name=n, cost=[t if ch=='T' else 'mushoku' for ch in cost], dmg=d, fx=fx) for n, cost, d, fx in atks],
        flav=flav, years=c['years'], region=c['region'], person=c['person'], art=artfile,
        artist=a, lic=lic, src=c['src']))
for c in base['trainers']:
    no = c['no']; rar, fx, flav = T[no]
    artfile = f"{no}.jpg"
    if not os.path.exists(os.path.join(ART, artfile)) or '--force' in sys.argv:
        center_crop(c['img']).save(os.path.join(ART, artfile), quality=84)
    a, lic = credit(c)
    cards.append(dict(id=no, kind=KIND[c['kind']], name=c['name'], rar=rar, fx=fx, flav=flav, art=artfile, artist=a, lic=lic, src=c['src']))
for k, t in TYPE.items():
    cards.append(dict(id='E-'+t, kind='energy', name=k+'エネルギー', type=t, rar=0))
for c in cards:
    if 'from_' in c: c['from'] = c.pop('from_')
out = os.path.join(ROOT, 'game', 'data.js')
open(out, 'w').write('// generated by tools/build_data.py\nwindow.HISTORIA_CARDS=' + json.dumps(cards, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(cards), 'cards ->', out)
