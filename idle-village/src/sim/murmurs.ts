const NIGHT = ['おやすみ…', 'ふわぁ…', '星がきれい'];
const HUNGRY = ['おなかすいた…', '肉が足りないよ', 'ぐぅ〜'];
const RAID = ['盗賊だー!', '逃げろー!', '隠れなきゃ!', 'こわいよ〜'];

export function murmur(v: Villager, ctx: { night: boolean; raid: boolean; season: number }): string | null {
  if (ctx.raid) return pick(RAID);
  if (v.hunger > 0.85) return pick(HUNGRY);
  if (ctx.night) return pick(NIGHT);
  const r = Math.random();
  if (r < 0.35) return pick(BY_TRAIT[v.trait]);
  if (r < 0.45) {
    return pick([
      ['春の風だ', '花が咲いてる', '新しい季節だね'],
      ['暑い〜', '海で泳ぎたい', '夏はいいね'],
      ['葉っぱが色づいてきた', '実りの秋!', '少し涼しくなった'],
      ['さむい…', '薪をたくさん集めないと', '冬は木が育たないね'],
    ][ctx.season]);
  }
  const t = v.task?.type ?? 'wander';
  const arr = BY_TASK[t];
  return arr ? pick(arr) : null;
}

